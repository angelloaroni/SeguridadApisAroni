CREATE TABLE IF NOT EXISTS accounts (
    username VARCHAR(40) PRIMARY KEY,
    display_name VARCHAR(80) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('USER', 'AGENT'))
);
CREATE TABLE IF NOT EXISTS tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject VARCHAR(120) NOT NULL,
    owner VARCHAR(40) NOT NULL REFERENCES accounts(username),
    agent VARCHAR(40) REFERENCES accounts(username)
);
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    author VARCHAR(40) NOT NULL REFERENCES accounts(username),
    body VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
